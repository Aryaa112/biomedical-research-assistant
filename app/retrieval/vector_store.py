import json
from pathlib import Path


import chromadb


EMBEDDINGS_FILE = Path(
    "data/embeddings/embeddings.json"
)

VECTOR_STORE_DIR = Path(
    "data/vector_store/chroma"
)

COLLECTION_NAME = "biomedical_chunks"


class BiomedicalVectorStore:
    """
    Persistent ChromaDB vector store for the
    biomedical research corpus.

    Responsibilities:
    - Load persisted embeddings
    - Create/connect to ChromaDB
    - Store embeddings with metadata
    - Provide access to the collection
    """

    def __init__(
        self,
        embeddings_file: Path = EMBEDDINGS_FILE,
        persist_directory: Path = VECTOR_STORE_DIR,
    ):

        self.embeddings_file = embeddings_file
        self.persist_directory = persist_directory

        # Ensure persistence directory exists
        self.persist_directory.mkdir(
            parents=True,
            exist_ok=True,
        )

        # Persistent Chroma client
        self.client = chromadb.PersistentClient(
            path=str(self.persist_directory)
        )

        # Get existing collection or create it
        self.collection = (
            self.client.get_or_create_collection(
                name=COLLECTION_NAME
            )
        )

    # ------------------------------------------------------------------
    # LOAD PERSISTED EMBEDDINGS
    # ------------------------------------------------------------------

    def load_embeddings(self) -> list[dict]:
        """
        Load embeddings previously generated by
        the D3 embedding pipeline.
        """

        if not self.embeddings_file.exists():
            raise FileNotFoundError(
                f"Embeddings file not found: "
                f"{self.embeddings_file}"
            )

        with open(
            self.embeddings_file,
            "r",
            encoding="utf-8",
        ) as f:

            data = json.load(f)

        if "embeddings" not in data:
            raise ValueError(
                "Invalid embeddings file: "
                "'embeddings' key not found."
            )

        return data["embeddings"]

    # ------------------------------------------------------------------
    # BUILD / UPDATE VECTOR STORE
    # ------------------------------------------------------------------

    def build(self) -> None:
        """
        Load persisted embeddings and upsert them
        into ChromaDB.

        Because upsert() is used, running this again
        does not create duplicate chunks.
        """

        records = self.load_embeddings()

        print(
            f"Found {len(records)} persisted embeddings."
        )

        if not records:
            raise ValueError(
                "No embeddings found."
            )

        ids = []
        embeddings = []
        documents = []
        metadatas = []

        for record in records:

            # Stable chunk identifier
            chunk_id = (
                f"{record['document_id']}"
                f"_{record['page_number']}"
                f"_{record['chunk_index']}"
            )

            ids.append(chunk_id)

            embeddings.append(
                record["embedding"]
            )

            documents.append(
                record["source_text"]
            )

            metadatas.append(
                {
                    "document_id": record[
                        "document_id"
                    ],
                    "page_number": record[
                        "page_number"
                    ],
                    "chunk_index": record[
                        "chunk_index"
                    ],
                    "content_hash": record[
                        "content_hash"
                    ],
                    "chunking_strategy": record[
                        "chunking_strategy"
                    ],
                }
            )

        # Upsert makes the operation safe to repeat
        self.collection.upsert(
            ids=ids,
            embeddings=embeddings,
            documents=documents,
            metadatas=metadatas,
        )

        print()
        print("=" * 70)
        print("VECTOR STORE READY")
        print("=" * 70)

        print(
            f"Collection: {COLLECTION_NAME}"
        )

        print(
            f"Stored chunks: "
            f"{self.collection.count()}"
        )

        print(
            f"Persisted at: "
            f"{self.persist_directory}"
        )